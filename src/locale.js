/** Country of the network opening the page. Null when the lookup does not answer. */
export async function detectCountryLocale() {
  const res = await fetch('https://api.country.is/', { cache: 'no-store' });
  if (!res.ok) return null;
  const data = await res.json();
  return localeFromCountry(data?.country);
}

